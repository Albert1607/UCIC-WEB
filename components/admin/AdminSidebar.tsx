export default function AdminSidebar() {
  const pathname = usePathname()
  const router = useRouter()
  const [mobileOpen, setMobileOpen] = useState(false)

  const handleLogout = async () => {
    const supabase = createClient()
    await supabase.auth.signOut()
    router.push('/admin/login')
    router.refresh()
  }

  const isActive = (item: typeof navItems[0]) => {
    if (item.exact) return pathname === item.href
    return pathname.startsWith(item.href)
  }

  const NavLinks = () => (
    <>
      {navItems.map((item) => (
        <Link
          key={item.href}
          href={item.href}
          className={`admin-sidebar-link ${isActive(item) ? 'active' : ''}`}
          onClick={() => setMobileOpen(false)}
        >
          {item.icon}
          {item.label}
        </Link>
      ))}
    </>
  )

  return (
    <>
      {/* Desktop sidebar */}
      <aside
        className="hidden md:flex flex-col w-56 min-h-screen shrink-0 admin-sidebar"
      >
        {/* Logo */}
        <div className="px-5 pt-8 pb-6 border-b" style={{ borderColor: 'rgba(156,182,215,0.12)' }}>
          <div
            className="heading-display text-2xl"
            style={{ color: 'var(--color-cream)' }}
          >
            UCIC
          </div>
          <div
            className="text-xs opacity-40 mt-0.5"
            style={{ color: 'var(--color-pale-blue)' }}
          >
            Admin Dashboard
          </div>
        </div>

        {/* Nav */}
        <nav className="flex-1 px-3 py-4 space-y-1 overflow-y-auto">
          <NavLinks />
        </nav>

        {/* Logout */}
        <div className="px-3 py-4 border-t" style={{ borderColor: 'rgba(156,182,215,0.12)' }}>
          <button
            onClick={handleLogout}
            className="admin-sidebar-link w-full text-left"
          >
            <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
              <path d="M9 21H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h4M16 17l5-5-5-5M21 12H9" />
            </svg>
            Sign Out
          </button>
        </div>
      </aside>

      {/* Mobile top bar */}
      <div
        className="md:hidden fixed top-0 left-0 right-0 z-40 flex items-center justify-between px-4 py-3"
        style={{ background: 'var(--color-navy)' }}
      >
        <span className="heading-display text-xl" style={{ color: 'var(--color-cream)' }}>
          UCIC Admin
        </span>
        <button
          onClick={() => setMobileOpen(!mobileOpen)}
          style={{ color: 'var(--color-pale-blue)' }}
          aria-label="Toggle menu"
        >
          {mobileOpen ? (
            <svg width="22" height="22" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
              <path d="M18 6L6 18M6 6l12 12" />
            </svg>
          ) : (
            <svg width="22" height="22" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
              <path d="M3 12h18M3 6h18M3 18h18" />
            </svg>
          )}
        </button>
      </div>

      {/* Mobile drawer */}
      {mobileOpen && (
        <div
          className="md:hidden fixed inset-0 z-30 pt-14"
          style={{ background: 'rgba(47,71,95,0.95)' }}
        >
          <nav className="px-4 py-4 space-y-1">
            <NavLinks />
            <button
              onClick={handleLogout}
              className="admin-sidebar-link w-full text-left mt-4"
            >
              <svg width="18" height="18" viewBox="0 0 24 24" fill="none" stroke="currentColor" strokeWidth="2">
                <path d="M9 21H5a2 2 0 0 1-2-2V5a2 2 0 0 1 2-2h4M16 17l5-5-5-5M21 12H9" />
              </svg>
              Sign Out
            </button>
          </nav>
        </div>
      )}
    </>
  )
}
